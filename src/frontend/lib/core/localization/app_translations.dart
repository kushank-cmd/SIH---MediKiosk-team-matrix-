  /// Translates a key with optional dynamic placeholder arguments.
  static String translate(String key, {Map<String, String>? args}) {
    String? text = _localizedValues[currentLanguage]?[key];

    // Fallback to English if not found in target language dictionary
    text ??= _localizedValues['en']?[key] ?? key;

    // Replace @placeholder tokens if args are provided
    if (args != null && args.isNotEmpty) {
      args.forEach((placeholder, value) {
        text = text!.replaceAll('@$placeholder', value);
      });
    }

    return text!;
  }

  /// Injects translated strings dynamically from Bhashini API responses.
  static void injectTranslations(String languageCode, Map<String, String> newTranslations) {
    if (!_localizedValues.containsKey(languageCode)) {
      _localizedValues[languageCode] = {};
    }
    _localizedValues[languageCode]!.addAll(newTranslations);
  }
